# Regenerate src/topics/meta.j: the draft 2020-12 meta-schema and its seven
# vocabulary meta-schemas, as published at json-schema.org, embedded verbatim.
#
# A schema may `$ref` the meta-schema (and some of the test suite does), and
# nothing may be fetched at validation time, so the deck carries its own copy.
# The documents are BSD-3-Clause; the notice travels with them in the file.
#
# Usage: tools/gen-meta.sh
set -euo pipefail
cd "$(dirname "$0")/.."

base=https://json-schema.org/draft/2020-12
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

curl -sfL -o "$work/schema" "$base/schema"
names=(core applicator unevaluated validation meta-data format-annotation content)
for n in "${names[@]}"; do
    curl -sfL -o "$work/$n" "$base/meta/$n"
done
curl -sfL -o "$work/LICENSE" \
    https://raw.githubusercontent.com/json-schema-org/json-schema-spec/main/LICENSE

python3 - "$work" "${names[@]}" > src/topics/meta.j <<'PY'
import json, sys

work, names = sys.argv[1], sys.argv[2:]
docs = [('schema', 'META_SCHEMA')] + [
    (n, 'META_' + n.upper().replace('-', '')) for n in names]

print('''# SPDX-License-Identifier: LGPL-3.0-only
# SPDX-FileCopyrightText: Copyright (C) 2026 mplx <mplx@jennifer-lang.dev>
# pragma-jennifer-version: >=0.25.0
# ci-no-overlay - generated by tools/gen-meta.sh; data, not behaviour

# jsonschema - the draft 2020-12 meta-schemas, embedded so a `$ref` to one
# resolves without a network. `metaDocuments` lists them for the registry.
# Spliced into jsonschema.j via include - not a standalone module.
#
# The JSON documents below are the JSON Schema Specification Authors' work,
# reproduced unchanged under this licence:
#''')
for line in open(f'{work}/LICENSE', encoding='utf-8').read().rstrip().split('\n'):
    print(('# ' + line).rstrip())
for name, const in docs:
    text = open(f'{work}/{name}', encoding='utf-8').read().rstrip()
    json.loads(text)
    assert "'" not in text, name
    print(f"\n/** The `{name}` meta-schema. */\ndef const {const} as string init '{text}';")
print('''
/**
 * Every embedded meta-schema, in the order they are registered.
 *
 * @return {list of string} the documents, as JSON text
 */
func metaDocuments() {
    return [''' + ', '.join(c for _, c in docs) + '''];
}''')
PY
echo "wrote src/topics/meta.j"
